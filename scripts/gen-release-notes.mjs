#!/usr/bin/env node
// Generate frontend/src/generated/releaseNotes.ts from git history.
//
// A "release" is a merge to main (a merged PR) — or, for a squash/rebase
// workflow, a first-parent commit carrying a Conventional-Commit subject.
// Each release lists the changes it brought in, grouped by type. The result
// is baked into the SPA bundle so the footer build SHA can open the notes for
// exactly the running build, with no external calls (CSP-safe).
//
// A snapshot is COMMITTED so local `npm run build`/`tsc`/tests work without
// git; deploy_app.sh regenerates it from full history right before the image
// build, so the deployed bundle's notes always match the deployed commit.
//
// Emits a typed .ts module (not JSON) to stay clean under the app tsconfig
// (verbatimModuleSyntax, no resolveJsonModule).

import { execSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const OUT = resolve(ROOT, 'frontend/src/generated/releaseNotes.ts')
const MAX_RELEASES = 60 // cap the browsable history

// Conventional-Commit types worth surfacing to operators, mapped to headings.
// Everything else (chore/test/ci/build/style/…) is noise and dropped.
const TYPE_LABEL = {
  feat: 'Features',
  fix: 'Fixes',
  perf: 'Performance',
  refactor: 'Refactors',
  docs: 'Docs',
  revert: 'Reverts',
}
const CONVENTIONAL = /^(\w+)(?:\(([^)]+)\))?(!)?:\s+(.+?)(?:\s+\(#(\d+)\))?$/
const MERGE_PR = /^Merge pull request #(\d+) /

function git(args) {
  return execSync(`git ${args}`, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
}

function parseSubject(subject) {
  const m = CONVENTIONAL.exec(subject.trim())
  if (m === null) return null
  const [, type, scope, bang, description, pr] = m
  const label = TYPE_LABEL[type]
  if (label === undefined) return null // drop non-surfaced types
  return {
    type,
    label,
    scope: scope ?? null,
    breaking: bang === '!',
    subject: description,
    pr: pr !== undefined ? Number(pr) : null,
  }
}

// The conventional changes a merge commit brought in: commits reachable from
// the merged branch (^2) but not from main before the merge (^1).
function mergeChanges(mergeSha) {
  let out
  try {
    out = git(`log ${mergeSha}^1..${mergeSha}^2 --no-merges --pretty=%s`)
  } catch {
    return []
  }
  return out
    .split('\n')
    .map(parseSubject)
    .filter((c) => c !== null)
}

function collectReleases() {
  const US = '\x1f'
  const RS = '\x1e'
  const raw = git(`log --first-parent -n 400 --pretty=%h${US}%cI${US}%P${US}%s${RS}`)
  const releases = []
  for (const line of raw.split(RS)) {
    if (line.trim() === '') continue
    const [sha, iso, parents, subject] = line.trim().split(US)
    const date = iso.slice(0, 10)
    const mergeMatch = MERGE_PR.exec(subject)
    if (mergeMatch !== null && parents.split(' ').length > 1) {
      const changes = mergeChanges(sha)
      if (changes.length === 0) continue // nothing operator-facing in this PR
      releases.push({ sha, date, pr: Number(mergeMatch[1]), changes })
    } else {
      const parsed = parseSubject(subject) // squash/rebase or direct commit
      if (parsed === null) continue
      releases.push({ sha, date, pr: parsed.pr, changes: [parsed] })
    }
    if (releases.length >= MAX_RELEASES) break
  }
  return releases
}

function render(releases) {
  return `// AUTO-GENERATED by scripts/gen-release-notes.mjs — do not edit by hand.
// Regenerated from git history on every deploy; a snapshot is committed so the
// SPA builds without git. See scripts/gen-release-notes.mjs.

export type ReleaseChange = {
  type: string
  label: string
  scope: string | null
  breaking: boolean
  subject: string
  pr: number | null
}

export type Release = {
  sha: string
  date: string
  pr: number | null
  changes: ReleaseChange[]
}

export const releases: Release[] = ${JSON.stringify(releases, null, 2)}
`
}

const releases = collectReleases()
mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, render(releases))
process.stderr.write(`release notes: ${releases.length} releases -> ${OUT}\n`)
